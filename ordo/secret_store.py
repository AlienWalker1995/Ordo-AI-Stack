@dataclasses.dataclass(frozen=True)
class SecretFile:
    """A file-delivered secret one service mounts: the store key whose value is written to
    out/secrets/<file> (ordo/secret_files.py). Services that read the same key share the file."""
    key: str
    file: str
    service: str


@dataclasses.dataclass(frozen=True)
class SecretNeeds:
    """The secret NAMES a render needs: env-form (`required`, of which `optional` may stay blank)
    and file-form (`files`)."""
    required: tuple[str, ...]
    optional: tuple[str, ...] = ()
    files: tuple[SecretFile, ...] = ()

    @classmethod
    def from_manifest(cls, manifest: Mapping[str, Any]) -> SecretNeeds:
        return cls(required=tuple(manifest.get("required_secrets") or ()),
                   optional=tuple(manifest.get("optional_secrets") or ()),
                   files=tuple(SecretFile(**entry) for entry in manifest.get("secret_files") or ()))

    @classmethod
    def from_render(cls, rendered: Any) -> SecretNeeds:
        return cls.from_manifest(rendered.manifest())


@dataclasses.dataclass
class Materialized:
    secrets_env: Path
    blank_required: list[str]
    blank_optional: list[str]
    files: list[Path]
    # Files under out/secrets/ that no render declares any more. Kept: a running container may still
    # mount one, and a restart of that container needs its bind source to exist. Remove one after
    # recreating the services that used it.
    stale_files: list[Path] = dataclasses.field(default_factory=list)


# The file-secret directory is owner-only on the host; each file in it is world-readable, because a
# bind-mounted file keeps its host mode and a container reads it as its own uid (oauth2-proxy runs as
# 65532, gpu-gate as 10001). The directory, not the file, is what keeps other host users out.
SECRET_FILES_DIR_MODE = 0o700
SECRET_FILE_MODE = 0o644


def _write_file_secrets(out: Path, files: Sequence[SecretFile], values: Mapping[str, str]) -> tuple[list[Path], list[Path]]:
    """Write each declared file secret once, and the digests every compose call loads. Returns
    (written files, stale files)."""
    by_file = {secret.file: secret.key for secret in files}
    directory = out / "secrets"
    directory.mkdir(parents=True, exist_ok=True)
    os.chmod(directory, SECRET_FILES_DIR_MODE)
    written = []
    for file, key in by_file.items():
        path = directory / file
        _write_owner_only(path, values.get(key, ""), mode=SECRET_FILE_MODE)
        written.append(path)
    stale = sorted(p for p in directory.iterdir()
                   if p.is_file() and not p.name.startswith(".") and p.name not in by_file)
    digests = [
        "# GENERATED by `ordo secrets materialize`: a digest of each file secret's value (never the value).",
        "# Each mount's label interpolates its digest, so a rotated value recreates its readers.",
    ]
    digests += [f"{secret_files.digest_var(key)}={secret_files.digest(values.get(key, ''))}"
                for key in sorted(set(by_file.values()))]
    _write_owner_only(out / secret_files.DIGESTS_ENV_FILE, "\n".join(digests) + "\n")
    return written, stale


def materialize(store: Store, needs: SecretNeeds, out_dir: Path, *, strict: bool = True,
                removed: Iterable[str] = ()) -> Materialized:
    """Write what the render needs from the store: out/secrets.env (from a SOPS store; a plain store
    already is that file), each file-delivered secret under out/secrets/, and their digests in
    out/secret-files.env.

    `strict` raises MissingSecrets (nothing written) when a required, non-optional key has no value;
    a writer that only reports blanks passes strict=False. A SOPS materialize refuses (LiveOnlySecrets,
    nothing written) to overwrite a value in out/secrets.env the store lacks, except the keys a writer
    just `removed` from the store on purpose."""
    out = Path(out_dir)
    values = parse_dotenv(store.read_text())
    blank_required = [k for k in needs.required if k not in needs.optional and not values.get(k)]
    blank_optional = [k for k in needs.required if k in needs.optional and not values.get(k)]
    if strict and blank_required:
        raise MissingSecrets(blank_required, store.description)
    secrets_env = out / "secrets.env"
    if store.materializes:
        live = parse_dotenv(secrets_env.read_text(encoding="utf-8")) if secrets_env.exists() else {}
        skip = set(removed)
        lost = [k for k, v in live.items() if v and not values.get(k) and k not in skip]
        if lost:
            raise LiveOnlySecrets(lost, store.description, store.live_only_fix)
    files, stale = _write_file_secrets(out, needs.files, values)
    if store.materializes:
        lines = [
            f"# GENERATED by `ordo secrets materialize` from {store.label}. Do not edit: the next",
            "# materialize replaces this file. Change a value with `ordo secrets set KEY`.",
        ]
        lines += [f"{k}={values.get(k, '')}" for k in needs.required]
        lines += [f"{k}={values[k]}" for k in OPTIONAL_SECRET_KEYS if values.get(k) and k not in needs.required]
        _write_owner_only(secrets_env, "\n".join(lines) + "\n")
    return Materialized(secrets_env, blank_required, blank_optional, files, stale)


