def _entry(line: str) -> tuple[str, str] | None:
    """(key, value) for a `KEY=value` line; None for a comment, a blank line or anything else."""
    if line.lstrip().startswith("#"):
        return None
    key, sep, value = line.partition("=")
    key = key.strip()
    if not sep or not key:
        return None
    return key, value.strip()


def parse_dotenv(text: str) -> dict[str, str]:
    """{KEY: value} in file order. The value is everything after the first `=`, trimmed."""
    values: dict[str, str] = {}
    for line in text.splitlines():
        entry = _entry(line)
        if entry is not None:
            values[entry[0]] = entry[1]
    return values


def update_dotenv(text: str, required_keys: Iterable[str], provided: Mapping[str, str] | None = None,
                  remove: Iterable[str] | None = None) -> tuple[str, list[str], list[str]]:
    """Bring dotenv `text` up to `required_keys`, line by line.

    A provided value replaces the key's value; a required key that is absent or blank gets a
    generated value when it is an internal secret, else an empty entry; a key in `remove` is
    dropped. Every other line (existing values, comments) is kept as is.
    Returns (new text, generated keys, keys left blank)."""
    provided = {k: str(v).strip() for k, v in (provided or {}).items() if str(v or "").strip()}
    drop = set(remove or [])
    existing: dict[str, str] = {}
    kept: list[str] = []
    for line in text.splitlines():
        entry = _entry(line)
        if entry is not None:
            key, value = entry
            if key in drop:
                continue
            existing[key] = value
            if key in provided:
                line = f"{key}={provided[key]}"
        kept.append(line)
    generated: list[str] = []
    blank: list[str] = []
    for key in dict.fromkeys([*required_keys, *provided]):
        if key in provided or existing.get(key):
            if key in provided and key not in existing:
                kept.append(f"{key}={provided[key]}")
            continue
        generator = generator_for(key)
        value = generator() if generator is not None else ""
        (generated if value else blank).append(key)
        if key in existing:   # present but blank: fill that line in place
            kept = [f"{key}={value}" if (_entry(ln) or ("",))[0] == key else ln for ln in kept]
        else:
            kept.append(f"{key}={value}")
    return ("\n".join(kept) + "\n" if kept else ""), generated, blank


def _write_owner_only(path: Path, text: str, mode: int = 0o600) -> None:
    """Write `text` to `path` atomically (temp file in the same directory, then replace), mode 0600
    unless `mode` says otherwise."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


