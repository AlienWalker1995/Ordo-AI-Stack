# edits: update, set, rotate, import
# --------------------------------------------------------------------------- #


def update(store: Store, required_keys: Iterable[str], provided: Mapping[str, str] | None = None,
           remove: Iterable[str] | None = None) -> tuple[list[str], list[str]]:
    """`update_dotenv` applied to the store; written only when something changed (a SOPS file is
    not re-encrypted, and so not churned in git, by a no-op). Returns (generated, blank) keys."""
    text = store.read_text()
    new_text, generated, blank = update_dotenv(text, required_keys, provided, remove)
    if new_text != text:
        store.write_text(new_text)
    return generated, blank


def rotation_refusal(key: str) -> str | None:
    """Why `key` must not be rotated from the store, or None when it may be."""
    if key in NEVER_ROTATE:
        return f"{key}: never rotate: {NEVER_ROTATE[key]}"
    if key in ISSUED_ELSEWHERE:
        return f"{key}: {ISSUED_ELSEWHERE[key]}"
    if generator_for(key) is None:
        return f"{key} is issued by an outside service: regenerate it there, then `ordo secrets set {key} --from-stdin`"
    return None


def is_internal(key: str) -> bool:
    return key in INTERNAL_ROTATION or key.startswith(INTERNAL_ROTATION_PREFIXES)


def rotate(store: Store, keys: Sequence[str]) -> list[str]:
    """Give each key a fresh generated value. Refuses (SecretStoreError, nothing written) a key the
    policy protects or one the store does not hold (a new key is `set --generate`)."""
    present = parse_dotenv(store.read_text())
    problems = [r for k in keys if (r := rotation_refusal(k))]
    problems += [f"{k} is not in {store.description} (add it with `ordo secrets set {k} --generate`)"
                 for k in keys if not rotation_refusal(k) and not present.get(k)]
    if problems:
        raise SecretStoreError("; ".join(problems))
    fresh = {key: generator_for(key)() for key in keys}   # rotation_refusal checked each has one
    update(store, [], provided=fresh)
    return list(keys)


def internal_keys(store: Store) -> list[str]:
    """The keys `rotate --internal` rotates: every internal token the store holds a value for."""
    return [k for k, v in parse_dotenv(store.read_text()).items() if v and is_internal(k)]


@dataclasses.dataclass
class Imported:
    added: list[str]
    differing: list[str]
    files_added: list[str]


def import_values(store: Store, live_path: Path, *, files: Sequence[SecretFile] = (),
                  files_dir: Path | None = None, overwrite: bool = False) -> Imported:
    """Add to the store every non-empty value in `live_path` (out/secrets.env) it lacks, and each
    file-form secret found in `files_dir` (the retired OPERATOR_SECRETS_DIR). A key the store holds
    with a different value is named in `differing` and kept, unless `overwrite`. Creates the store
    when it does not exist."""
    text = store.read_text() if store.exists() else ""
    stored = parse_dotenv(text)
    live = parse_dotenv(Path(live_path).read_text(encoding="utf-8")) if Path(live_path).exists() else {}
    provided: dict[str, str] = {}
    added: list[str] = []
    differing: list[str] = []
    for key, value in live.items():
        if not value:
            continue
        if not stored.get(key):
            provided[key] = value
            added.append(key)
        elif stored[key] != value:
            differing.append(key)
            if overwrite:
                provided[key] = value
    files_added: list[str] = []
    for secret in files:
        path = Path(files_dir) / secret.file if files_dir else None
        if path is None or not path.is_file() or stored.get(secret.key) or secret.key in provided:
            continue
        value = path.read_text(encoding="utf-8").strip()
        if value:
            provided[secret.key] = value
            files_added.append(secret.key)
    if not provided and not store.exists():
        raise SecretStoreError(f"nothing to import: {live_path} holds no value, so {store.description} "
                               "was not created")
    if provided:
        new_text, _, _ = update_dotenv(text, [], provided=provided)
        store.write_text(new_text)
    return Imported(added, differing, files_added)


